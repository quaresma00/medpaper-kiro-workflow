"""1.15.0 (E4): the S25 independent audit converges.

On 1.14 every S25 audit read the whole package afresh and found 10-40 new minor items, some of
them engine-owned formatting the agent cannot change in the workflow (keep markers, the ESM
header, PDF language, CSL rendering, document properties). Now:

- the FIRST audit of a paper is full; later audits (re-audits after REVISE) check whether each
  previous finding is resolved plus NEW BLOCKING issues only (`package_review.py audit-start`
  picks the mode and writes the brief);
- engine-owned formatting is listed in the brief: such findings go under "Engine issues", are
  reported to the engine maintainer separately and never cause REVISE on their own;
- at the first REVISE the user is offered the author-final-copy route at once, with the open
  item list (`wf decide submission_package_independent_audit REVISE` prints it);
- preference items are closed as one group with one reason (`review_round.py close
  --preference-group "<reason>"`).

The reviewer writes its report to .wf/review_bundle/<A00n>/report.md (its only writable
file); `package_review.py audit-save` copies it verbatim to
08_submission/independent_submission_audit.md after the review guard (wfcore/reviewguard.py).
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

AUDIT_REL = "08_submission/independent_submission_audit.md"
HISTORY_DIR = ".wf/audits"
BUNDLE_DIR = ".wf/review_bundle"
FREEZE_RE = re.compile(r"Freeze ID:\s*`?([0-9a-fA-F]{8,64})")
FINDING_LINE = re.compile(r"(?i)\b(BLOCKING|MINOR|PREFERENCE)\b")

ENGINE_OWNED = (
    "table keep-with-next/keepLines markers and black squares in Word (engine default: none)",
    "the 'Online Resource n' / supplementary information header layout",
    "PDF /Lang and PDF export settings",
    "reference-list rendering by the journal CSL (punctuation, page ranges, '; discussion' "
    "suffixes, et al. rules)",
    "Word document properties (docProps/custom.xml, core/app metadata)",
    "build-receipt, manifest and checklist file formats generated by the engine",
)

SECTIONS = ("Verdict", "Reader comprehension", "Editorial screening and low-level errors",
            "Guideline compliance", "Required files and omissions", "Cross-file consistency",
            "Formatting and technical checks", "Issues requiring correction",
            "Final recommendation")

FULL_BRIEF = """S25 independent audit ({aid}, FULL - first audit for this journal). Read every file
listed below in normal submission order before any QA file, as a first-time reader, an editor
and a journal-compliance reviewer. Report in exactly these sections: {sections}. Under
Verdict write `Freeze ID: {freeze}`. Number every finding (F1, F2, ...), name file and
location, and classify it BLOCKING, MINOR or PREFERENCE.
{engine}
Write your complete report to {report} - the only file you may write. If you cannot write it,
return it between <<<REPORT>>> and <<<END>>>."""

RECHECK_BRIEF = """S25 re-audit ({aid}, RE-AUDIT after REVISE). This is NOT a fresh full audit.
1. For every finding in previous_findings.md say RESOLVED or OPEN (file + location).
2. Report NEW issues only if they are BLOCKING (a required file, fact, rule or a number/claim
   that is wrong). New minor or preference remarks are out of scope for this re-audit.
Report in exactly these sections: {sections}. Under Verdict write `Freeze ID: {freeze}`.
Verdict PASS when every previous BLOCKING/MINOR finding is RESOLVED (or listed as an engine
issue) and there is no new BLOCKING issue.
{engine}
Write your complete report to {report} - the only file you may write. If you cannot write it,
return it between <<<REPORT>>> and <<<END>>>."""


CHECKLIST_ORDER = ("Reporting checklists and forms are numbered after the content supplementary "
                   "files and are exempt from first-citation ordering; do not ask to move a "
                   "citation only to satisfy numbering (1.15.0). Digits inside the reference "
                   "list are verified against PubMed by the engine, not by you.")


MATRIX_FULL = """Compliance (1.18.0): 08_submission/guideline_requirements.json lists the journal's
requirements with verbatim quotes and line numbers; 08_submission/compliance_matrix.md has one
row per requirement. Under "Guideline compliance" write one line per matrix row:
`- <row id>: agree|disagree - <reason>` (check each row against guidelines_source.txt and the
package itself, not against the matrix's own evidence). Then read guidelines_source.txt and the
cached originals for obligations (must, required, should, maximum, no more than ...) that the
list lacks; report each under "Required files and omissions" as
`- MISSING L00nn: "<quote>" - BLOCKING`. A missing or contradicted requirement is BLOCKING.
CANNOT_ASSESS and portal rows are user/portal items: list them, they are never a reason for
REVISE by themselves."""

MATRIX_RECHECK = """Compliance (1.18.0): re-check ONLY the matrix rows in open_rows.md
(`- <row id>: agree|disagree - <reason>` each) plus any NEW missing requirement
(`- MISSING L00nn: "<quote>" - BLOCKING`). CANNOT_ASSESS/portal rows are user items, not REVISE."""


def required_rows(project: Path, matrix: dict) -> list[str]:
    """Matrix rows the current audit must judge: all (full audit) or the open ones (re-audit,
    rows_required.json in the latest bundle)."""
    ids = [str(r.get("id")) for r in matrix.get("rows") or []]
    bundle = latest_bundle(project)
    data = None
    if bundle is not None and (bundle / "rows_required.json").is_file():
        try:
            data = json.loads((bundle / "rows_required.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            data = None
    if isinstance(data, list):
        return [i for i in ids if i in set(map(str, data))]
    return ids


def _matrix_rows(project: Path, out: Path, mode: str, prev_text: str) -> str:
    """Write rows_required.json (+ open_rows.md for a re-audit); return the brief paragraph."""
    from . import compliance
    try:
        data = json.loads((Path(project) / compliance.MATRIX_JSON).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    rows = data.get("rows") or []
    ids = [str(r.get("id")) for r in rows]
    if mode != "recheck":
        (out / "rows_required.json").write_text(json.dumps(ids) + "\n", encoding="utf-8")
        return MATRIX_FULL
    from .checks.v1180 import row_verdicts
    got = row_verdicts(prev_text, ids)
    open_ids = [r["id"] for r in rows if got.get(r["id"], ("none",))[0] != "agree"
                or r.get("status") in ("FAIL", "WARN")]
    (out / "rows_required.json").write_text(json.dumps(open_ids) + "\n", encoding="utf-8")
    lines = ["# Open compliance rows (re-check only these)", ""]
    lines += [f"- {r['id']} [{r['status']}] {r.get('lines')}: {r.get('quote')} | previous verdict: "
              f"{got.get(r['id'], ('none',))[0]}" for r in rows if r["id"] in open_ids] or ["- none"]
    (out / "open_rows.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return MATRIX_RECHECK


def engine_text() -> str:
    return ("Engine-owned formatting (report under a separate heading 'Engine issues'; never a "
            "reason for REVISE by itself): " + "; ".join(ENGINE_OWNED) + ". " + CHECKLIST_ORDER)


def freeze_id(project: Path) -> str:
    try:
        return str(json.loads((Path(project) / "08_submission/package_review_freeze.json")
                              .read_text(encoding="utf-8")).get("freeze_id", ""))
    except (OSError, ValueError):
        return ""


def history(project: Path) -> list[Path]:
    root = Path(project) / HISTORY_DIR
    return sorted(root.glob("A*.md")) if root.is_dir() else []


EPOCH_INDEX = ".wf/audits/epochs.json"


def _epoch_index(project: Path) -> dict:
    try:
        data = json.loads((Path(project) / EPOCH_INDEX).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def epoch_history(project: Path) -> list[Path]:
    """1.17.0 (J1): earlier audits of the CURRENT journal epoch only. An audit of an earlier
    journal (by its recorded journal/epoch, or for legacy audits by date) never turns the first
    audit of a new journal into a re-check of the old findings."""
    from . import journalepoch
    idx = _epoch_index(project)
    name = journalepoch.norm(journalepoch.target_name(project))
    ep = journalepoch.number(project)
    start = journalepoch.started_at(project)
    out = []
    for h in history(project):
        rec = idx.get(h.name)
        if isinstance(rec, dict):
            if int(rec.get("epoch") or 1) == ep and (not name or not rec.get("journal")
                                                     or journalepoch.norm(rec["journal"]) == name):
                out.append(h)
        elif start is None or h.stat().st_mtime >= start - 1:
            out.append(h)
    return out


def findings(text: str) -> list[str]:
    """Finding lines (BLOCKING / MINOR / PREFERENCE) of an audit report, verbatim."""
    out = []
    for line in (text or "").splitlines():
        s = line.strip()
        if s and FINDING_LINE.search(s) and (re.match(r"^[-*|#\s]*\**F\d+", s) or
                                             re.match(r"^[-*]\s", s) or s.startswith("|")):
            out.append(s)
    return out


def guideline_files(project: Path) -> list[str]:
    """1.17.0 (J1): the journal's original guide for the auditor - the line-numbered
    guidelines_source.txt and the cached originals of this journal epoch (all cache files for
    snapshots taken before 1.17.0)."""
    from . import guideingest, journalepoch
    project = Path(project)
    originals = [f"08_submission/cache/{e['file']}" for e in guideingest.entries(
        project, "guidelines", journalepoch.number(project))]
    if not originals:
        originals = [p.relative_to(project).as_posix() for p in
                     sorted((project / "08_submission/cache").glob("*"))
                     if p.is_file() and p.name != "index.json"]
    return ["08_submission/guidelines_source.txt", *originals]


def open_items(text: str) -> list[str]:
    """BLOCKING and MINOR finding lines (what the author would still fix)."""
    return [x for x in findings(text) if re.search(r"(?i)\b(BLOCKING|MINOR)\b", x)
            and not re.search(r"(?i)\bRESOLVED\b", x)]


def _archive_current(project: Path, current_freeze: str) -> None:
    """Keep the audit on disk (if it belongs to an earlier freeze) in .wf/audits/."""
    path = Path(project) / AUDIT_REL
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8", errors="replace")
    m = FREEZE_RE.search(text)
    fid = m.group(1) if m else "unknown"
    if fid == current_freeze:
        return
    if any(h.read_text(encoding="utf-8", errors="replace") == text for h in history(project)):
        return
    dest = Path(project) / HISTORY_DIR / f"A{len(history(project)) + 1:03d}_{fid[:12]}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
    from . import journalepoch
    idx = _epoch_index(project)
    idx[dest.name] = {"journal": journalepoch.target_name(project),
                      "epoch": journalepoch.number(project), "freeze": fid}
    (Path(project) / EPOCH_INDEX).write_text(json.dumps(idx, indent=2, ensure_ascii=False) + "\n",
                                             encoding="utf-8")


def start(project: Path, files: list[str]) -> tuple[Path, str]:
    """Write the audit bundle (full or re-audit) and the review-guard snapshot."""
    from . import reviewguard
    project = Path(project)
    fid = freeze_id(project)
    _archive_current(project, fid)
    past = epoch_history(project)
    mode = "recheck" if past else "full"
    aid = f"A{len(history(project)) + 1:03d}"
    out = project / BUNDLE_DIR / aid
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    report = out / "report.md"
    brief = (RECHECK_BRIEF if mode == "recheck" else FULL_BRIEF).format(
        aid=aid, sections=", ".join(SECTIONS), freeze=fid, report=report, engine=engine_text())
    lines = [f"# S25 audit bundle {aid} ({mode})", "", brief, ""]
    from .declarations import ai_fact  # 1.15.0 (E10): a recorded fact, never "pending"
    fact = ai_fact(project)
    if fact:
        lines += [f"AI/LLM use is the author's recorded fact (not a pending item): "
                  f"{'used: ' + fact['tool'] + ' for ' + fact['purpose'] if fact['used'] else 'not used'}"
                  f". Statement: {fact['statement']}", ""]
    from .guidelines import status as _gstatus
    from .journalepoch import banner
    lines += [f"Guideline basis: 08_submission/guidelines_extract.md ({_gstatus(project)}), "
              "checked against the journal's own text: 08_submission/guidelines_source.txt "
              "(line-numbered L0001...) and the cached original guide files listed below. Judge "
              "compliance from the original, not from the extract alone.",
              f"{banner(project) or ''}", "", "## Files", ""]
    prev = past[-1].read_text(encoding="utf-8", errors="replace") if mode == "recheck" else ""
    para = _matrix_rows(project, out, mode, prev)
    if para:
        lines[3:3] = [para, ""]
    if mode == "recheck":
        items = findings(prev)
        (out / "previous_findings.md").write_text(
            f"# Findings of the previous audit ({past[-1].name})\n\n" + "\n".join(
                f"- {x}" for x in items) + "\n", encoding="utf-8")
        lines.append(f"- {out / 'previous_findings.md'} (check each: RESOLVED or OPEN)")
        if (out / "open_rows.md").is_file():
            lines.append(f"- {out / 'open_rows.md'} (compliance rows to re-check)")
    lines += [f"- {project / rel}" for rel in files if (project / rel).is_file()]
    from .reviewitems import write as _write_items  # 1.16.0: cases a gate could not decide
    listed = _write_items(project, out)
    if listed:
        lines.append(f"- {listed} (cases the deterministic checks could not decide)")
    (out / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    reviewguard.take(project, aid)
    return out, mode


def latest_bundle(project: Path) -> Path | None:
    root = Path(project) / BUNDLE_DIR
    found = sorted(p for p in root.glob("A[0-9][0-9][0-9]") if p.is_dir()) if root.is_dir() else []
    return found[-1] if found else None


def save(project: Path, src: Path | None = None) -> Path:
    """Copy the reviewer's report verbatim to 08_submission/independent_submission_audit.md."""
    from . import reviewguard
    project = Path(project)
    bundle = latest_bundle(project)
    if bundle is None:
        raise ValueError("no S25 audit bundle; run package_review.py audit-start first")
    report = bundle / "report.md"
    if src is not None:
        reviewguard.ingest(project, Path(src), report)
    if not report.is_file():
        raise ValueError(f"no report at {report}; the reviewer writes it there (or save its reply "
                         "and run audit-save --from <file>)")
    bad = reviewguard.problems(project, bundle.name, report)
    if bad:
        raise ValueError("paper file(s) changed while the audit was running: " + ", ".join(bad[:8])
                         + " - restore them and start the audit again")
    dest = project / AUDIT_REL
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(report, dest)
    return dest


def revise_offer(project: Path) -> list[str]:
    """Printed when the first REVISE is recorded: the author-final-copy route at once."""
    path = Path(project) / AUDIT_REL
    text = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else ""
    items = open_items(text)
    out = ["Offer the user BOTH routes now in one message (do not decide for them):",
           "  A) one S24 review round with these findings, a new freeze, then a RE-AUDIT that only "
           "checks these items plus new BLOCKING issues;",
           "  B) author final copy: the author fixes them by hand in 08_submission/final_copy/ "
           "(tools/final_copy.py record/check), then PASS_AUTHOR_FINAL_COPY.",
           f"Open items ({len(items)}):"]
    out += [f"  {x[:200]}" for x in items[:40]]
    return out
