def _hook(name: str, trigger: str, description: str, command: str, timeout: int,
          matcher: str | None = None) -> str:
    spec = {"name": name, "trigger": trigger}
    if matcher:
        spec["matcher"] = matcher
    spec["description"] = description
    spec["action"] = {"type": "command", "command": command, "timeout": timeout}
    return json.dumps({"version": "v1", "hooks": [spec]}, indent=2, ensure_ascii=False) + "\n"


def render_adapters(wf_cmd: str, tool_prefix: str, *, engine_workspace: bool,
                    engine: Path) -> list[tuple[str, str]]:
    if engine_workspace:
        steering = STEERING_ENGINE
        guard = "python tools/hooks/skill_guard.py"
    else:
        steering = STEERING_PAPER.substitute(wf=wf_cmd, tool=tool_prefix,
                                             engine=engine.as_posix())
        guard = f'python "{tool_prefix}hooks/skill_guard.py"'
    status = _hook(
        "medpaper: show pipeline state on session start", "SessionStart",
        "Prints the current pipeline stage, gate state and last handoff note at the start of "
        "every session, so the agent never has to guess where the work stopped.",
        f"{wf_cmd} status --brief", 60)
    skill_guard = _hook(
        "medpaper: block skills that replace a pipeline stage", "PreToolUse",
        "Refuses activation of skills that would substitute for a pipeline stage and leave its "
        "gate unsatisfiable (write-paper, orchestrate, make-figures, search-lit and others), and "
        "asks for confirmation on skills that merely overlap a stage. Decisions come from "
        "reference/skill_policy.toml.", guard, 30, matcher="disclose_context")
    frozen_cmd = ("python tools/hooks/frozen_guard.py" if engine_workspace
                  else f'python "{tool_prefix}hooks/frozen_guard.py"')
    frozen_guard = _hook(
        "medpaper: stop edits to frozen or certified sources", "PreToolUse",
        "Refuses a file write to a scientifically frozen or revision-certified source (for "
        "example a figure script at S23) unless an open revision round covers it, and names the "
        "rework.py command that opens one.", frozen_cmd, 30,
        matcher="fs_write|str_replace|fsWrite|strReplace|fsAppend|editCode")
    return [(".kiro/steering/medpaper-pipeline.md", steering),
            (".kiro/hooks/medpaper-status.json", status),
            (".kiro/hooks/medpaper-skill-guard.json", skill_guard),
            (".kiro/hooks/medpaper-frozen-guard.json", frozen_guard)]


def engine_adapters() -> list[tuple[str, str]]:
    return render_adapters("python tools/wf.py", "tools/", engine_workspace=True,
                           engine=paths.repo_root())


def paper_adapters(engine: Path) -> list[tuple[str, str]]:
    e = Path(engine).as_posix()
    return render_adapters(f'python "{e}/tools/wf.py"', f"{e}/tools/",
                           engine_workspace=False, engine=Path(engine))


def write_adapters(dest_root: Path, files, *, check: bool) -> list[tuple[str, str]]:
    dest_root = Path(dest_root).resolve()
    is_engine_files = [r for r, _ in files] == [r for r, _ in engine_adapters()] and \
        files == engine_adapters()
    if paths.in_engine(dest_root) and not (
            is_engine_files and paths.within(dest_root, paths.repo_root())
            and paths.within(paths.repo_root(), dest_root)):
        raise ValueError(f"refusing to write paper adapters into the engine: {dest_root}")
    rows = []
    for rel, content in files:
        p = dest_root / rel
        if check:
            if not p.exists():
                rows.append((rel, "MISSING"))
            else:
                rows.append((rel, "ok" if p.read_text(encoding="utf-8") == content else "STALE"))
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        existed = p.exists()
        if existed and p.read_text(encoding="utf-8") == content:
            rows.append((rel, "ok"))
            continue
        p.write_text(content, encoding="utf-8", newline="\n")
        rows.append((rel, "updated" if existed else "created"))
    return rows


