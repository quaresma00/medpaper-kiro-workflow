"""Measured submission checklist and QC block (1.8.0).

SUBMISSION_CHECKLIST.md once said "page numbers added" when the DOCX had none, and
submission_qc.md kept page counts from an earlier build. Both are now generated from tool
measurements of the current files on every rebuild; the gate regenerates them in memory and
fails on any difference or any FAIL row. The same measurements run at S23 (pre-audit), S24
and S25, so the independent audit confirms rather than discovers.
"""
from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

from . import docxaudit, journalspec

CHECKLIST_REL = "08_submission/bundle/SUBMISSION_CHECKLIST.md"
QC_REL = "08_submission/submission_qc.md"
MANIFEST_REL = "08_submission/bundle/manifest.json"
BEGIN, END = "<!-- measured:begin (generated by submission_qc.py; do not edit) -->", "<!-- measured:end -->"


def _sha(path: Path) -> str:
    from .revision import sha256
    return sha256(path)[:12]


def _xml_parts(path: Path) -> tuple[dict, object]:
    with zipfile.ZipFile(path) as zf:
        xmls = {n: zf.read(n) for n in zf.namelist()
                if n.startswith("word/") and n.endswith((".xml", ".rels"))}
    return xmls, ET.fromstring(xmls["word/document.xml"])


def row_status(problems, na: bool = False, warn: bool = False) -> str:
    """1.12.0 (A5): an advisory (warn-severity) result is a WARN row and never blocks."""
    if na:
        return "N/A"
    if not problems:
        return "PASS"
    return "WARN" if warn else "FAIL"


def measure(ctx) -> list[dict]:
    """Rows of {item, status PASS|FAIL|N/A, evidence}; deterministic for unchanged files."""
    from .checks import get, load_all
    from .checks.manuscript import declaration_and_discussion_problems
    from .checks.text import backstage_hits
    load_all()
    project = ctx.project
    rows: list[dict] = []

    def row(item, problems, evidence, na=False, warn=False):
        rows.append({"item": item, "status": row_status(problems, na, warn),
                     "evidence": ("; ".join(problems[:3]) if problems else evidence)})
    try:
        manifest = json.loads((project / MANIFEST_REL).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        manifest = {"items": []}
    items = [i for i in manifest.get("items", []) if str(i.get("file", "")) != CHECKLIST_REL]
    missing = [i.get("file") for i in items if not (project / str(i.get("file", ""))).is_file()]
    row("Every manifest upload exists", missing and [f"missing: {', '.join(map(str, missing))}"],
        f"{len(items)} upload(s)")
    docs = [(str(i.get("role", "")).casefold(), project / str(i.get("file", ""))) for i in items
            if str(i.get("file", "")).lower().endswith(".docx") and (project / str(i["file"])).is_file()]
    spec = docxaudit.audit_spec(project)
    pages, refs, legends, code = [], [], [], []
    for role, path in docs:
        xmls, root = _xml_parts(path)
        pages += [f"{path.name}: {p}" for p in docxaudit.footer_page_problems(xmls)]
        text = "\n".join(t for t, _, _ in docxaudit.paragraphs(root))
        code += [f"{path.name}: {p}" for p in docxaudit.pipeline_code_problems(text)]
        if _since_1141(ctx):  # 1.14.1 (B5): document properties too (docProps/*, customXml/*)
            code += [f"{path.name}: {p}" for p in docxaudit.docprops_problems(path)]
        if role == "manuscript":
            refs += docxaudit.reference_problems(root, spec["reference_separator"])
            legends += docxaudit.legend_problems(root, spec["main_figures"], 10 ** 6,
                                                 supplementary=spec["supp_figures"])
            legends += docxaudit.legend_style_problems(root, spec["legend_style"])
            legends += docxaudit.display_problems(root, spec, role)
    names = ", ".join(f"{p.name}@{_sha(p)}" for _, p in docs)
    row("Automatic page numbers in every DOCX footer", pages, names or "no DOCX", na=not docs)
    has_ms = any(r == "manuscript" for r, _ in docs)
    row("References: number + one space (no TAB/hanging indent unless the journal sets "
        "reference_separator \"tab\"), no dangling separators", refs,
        "manuscript references formatted", na=not has_ms)
    row("Figure legends: main figures only, journal legend style, display switches", legends,
        "consistent with target_journal.json", na=not has_ms)
    row("No pipeline code or local paths in uploads", code, "clean")
    rel = ctx.src("07_manuscript/full_manuscript.md")
    text = ctx.read(rel) if ctx.p(rel).is_file() else ""
    row("Declarations order and Discussion prose", declaration_and_discussion_problems(ctx, text)
        if text else ["full manuscript missing"], "journal order; continuous Discussion")
    leaks = []
    for name in ("07_manuscript/full_manuscript.md", "07_manuscript/supplementary_methods.md",
                 "07_manuscript/statements.md", "08_submission/cover_letter.md"):
        src = ctx.src(name) if name.startswith("07_") else name
        if ctx.p(src).is_file():
            from .checks.text import polish_allowed, unallowed  # 1.14.1 (B7)
            leaks += [f"{Path(src).name}: {h}" for h in
                      unallowed(backstage_hits(ctx.read(src)), polish_allowed(project))]
    row("No pipeline review/draft history in the text", leaks, "none found")
    try:
        import sys
        tools = Path(__file__).resolve().parents[1]
        if str(tools) not in sys.path:
            sys.path.insert(0, str(tools))
        from text import polish
        prose = [(src, ctx.read(src)) for src in (rel, ctx.src("07_manuscript/supplementary_methods.md"))
                 if ctx.p(src).is_file()]
        abbrev = [f"{x['file']} {x['detail']}" for x in
                  polish.lint_abbreviations(prose) + polish.lint_display_abbreviations(_display(project))
                  if x.get("severity") == "blocking"]
    except Exception as exc:  # noqa: BLE001 - report, never crash the checklist
        abbrev = [f"abbreviation lint failed: {exc}"]
    row("Abbreviations defined per scope (abstract, body, each table)", abbrev, "clean")
    target = journalspec.load(project)
    for name in ("journal_limits_met", "title_page_reference_count"):
        fn = get(name)
        res = fn(type(ctx)(ctx.pipeline, ctx.state, project, ctx.stage, {"check": name}))
        row({"journal_limits_met": "Word counts, references and display items within typed caps",
             "title_page_reference_count": "Title-page reference count matches citations"}[name],
            [] if res.ok else [res.detail], res.detail,
            warn=(not res.ok and res.severity == "warn"))
    supp = ctx.psrc("07_manuscript/supplementary_methods.md").is_file()
    pdf_needed = bool(target) and supp and journalspec.si_format(target) == "pdf"
    pdfs = [i for i in items if str(i.get("role", "")).casefold() == "supplementary_pdf"]
    row("Supplementary file in the journal's format", ["no supplementary_pdf upload"]
        if pdf_needed and not pdfs else [], f"si_format={journalspec.si_format(target)}",
        na=not supp)
    return rows


def _display(project: Path):
    import sys
    tools = Path(__file__).resolve().parents[1]
    if str(tools) not in sys.path:
        sys.path.insert(0, str(tools))
    from text import polish
    import os
    old = os.environ.get("MEDPAPER_PROJECT")
    os.environ["MEDPAPER_PROJECT"] = str(project)
    try:
        return polish.display_blocks()
    finally:
        if old is None:
            os.environ.pop("MEDPAPER_PROJECT", None)
        else:
            os.environ["MEDPAPER_PROJECT"] = old


def _table(rows: list[dict]) -> str:
    lines = ["| Check | Status | Measured evidence |", "|---|---|---|"]
    lines += [f"| {r['item']} | {r['status']} | {r['evidence'].replace('|', '/')[:300]} |" for r in rows]
    return "\n".join(lines)


def render_checklist(ctx, rows: list[dict]) -> str:
    try:
        manifest = json.loads((ctx.project / MANIFEST_REL).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        manifest = {"items": []}
    uploads = ["| Role | File | SHA-256 (12) | Required by |", "|---|---|---|---|"]
    for i in manifest.get("items", []):
        f = str(i.get("file", ""))
        if f == CHECKLIST_REL:
            continue
        p = ctx.project / f
        uploads.append(f"| {i.get('role', '')} | {Path(f).name} | {_sha(p) if p.is_file() else 'MISSING'} "
                       f"| {i.get('required_by', '')} |")
    return ("# Submission checklist\n\nGenerated by `tools/manuscript/submission_qc.py write` from "
            "measurements of the current files. Do not tick items by hand; rebuild and rerun.\n\n"
            "## Measured checks\n\n" + _table(rows) + "\n\n## Uploads\n\n" + "\n".join(uploads) + "\n")


def render_qc(existing: str, rows: list[dict]) -> str:
    block = f"{BEGIN}\n## Measured checks (regenerated on every rebuild)\n\n{_table(rows)}\n{END}"
    if BEGIN in existing and END in existing:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, existing, flags=re.S)
    head = existing.rstrip() + "\n\n" if existing.strip() else "# Submission QC\n\n"
    return head + block + "\n"


def _since_1141(ctx) -> bool:
    """Stricter measurements apply to a paper pinned before 1.14.1 only after wf migrate."""
    from .state import version_tuple
    try:
        return version_tuple(ctx.state.engine_pin) >= (1, 14, 1)
    except Exception:  # noqa: BLE001
        return True


def write(ctx) -> list[dict]:
    rows = measure(ctx)
    (ctx.project / CHECKLIST_REL).parent.mkdir(parents=True, exist_ok=True)
    (ctx.project / CHECKLIST_REL).write_text(render_checklist(ctx, rows), encoding="utf-8")
    qc = ctx.project / QC_REL
    qc.write_text(render_qc(qc.read_text(encoding="utf-8") if qc.is_file() else "", rows),
                  encoding="utf-8")
    from .revision import record_derived
    record_derived(ctx.project, [ctx.project / CHECKLIST_REL, qc])  # 1.14.1 (B2)
    return rows


def verify(ctx) -> list[str]:
    rows = measure(ctx)
    problems = [f"{r['item']}: {r['evidence']}" for r in rows if r["status"] == "FAIL"]
    cl, qc = ctx.project / CHECKLIST_REL, ctx.project / QC_REL
    if not cl.is_file() or cl.read_text(encoding="utf-8") != render_checklist(ctx, rows):
        problems.append("SUBMISSION_CHECKLIST.md is not the current measurement (hand-edited or "
                        "stale); run tools/manuscript/submission_qc.py write")
    if not qc.is_file() or render_qc(qc.read_text(encoding="utf-8"), rows) != qc.read_text(encoding="utf-8"):
        problems.append("submission_qc.md measured block is stale; run submission_qc.py write")
    return problems
